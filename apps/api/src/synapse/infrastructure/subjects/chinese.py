"""Chinese plugin: the third subject, at the NONE verifiability tier (M2.5 S7).

This plugin exists to hold the *other* promise. Math (STRONG) may name the step
a student skipped and attach a counterexample; physics (PARTIAL) may probe and
card on structured steps. Chinese has no automatic truth, so the product may
only show the reference structure and which steps the process appears to
mention. Everything else is refused by construction:

* ``level = NONE`` — ``application/commitment.py`` turns that into "no probes,
  no diagnosis card, structure hint only";
* ``probes_for`` returns nothing, so even a graph that somehow carries probes
  cannot start a probe turn;
* ``verify`` always answers ``unknown`` — there is no honest ``pass`` here;
* there is no annotated catalog: a submitted stem gets a generated graph.

The graph itself is generated by the shared ``LLMGraphGenerator`` with the
``graph-v6-chinese`` prompt, which asks for steps only (no probes, no claim).
"""

from __future__ import annotations

from collections.abc import Mapping

from synapse.application.graph import GraphBuildFailed, GraphGenerator
from synapse.application.subject import (
    EvidenceModel,
    ProblemRef,
    StudentStep,
    Verdict,
    VerifiabilityLevel,
)
from synapse.domain.problem.alignment import ClauseCueAligner, StepAligner
from synapse.domain.problem.models import (
    Probe,
    Problem,
    ProblemDraft,
    SolutionGraph,
    SolutionNode,
)

SUBJECT = "chinese"


class ChinesePlugin:
    subject = SUBJECT
    level = VerifiabilityLevel.NONE

    def __init__(
        self,
        catalog: Mapping[str, Problem] | None = None,
        *,
        generator: GraphGenerator | None = None,
        aligner: StepAligner | None = None,
    ) -> None:
        # No annotated Chinese problem set yet. The field exists so a reviewed
        # graph could be added later without changing the plugin's shape.
        self._catalog = dict(catalog or {})
        self._generator = generator
        # S8: prose nodes are multi-clause, so the whole-sentence 3-gram
        # backstop systematically undercounted. Clause matching adds a
        # ``partial`` answer instead of smoothing the threshold.
        self._aligner: StepAligner = aligner or ClauseCueAligner()

    def identify(self, text: str) -> ProblemRef | None:
        """No annotated Chinese catalog: generic routing is the resolver's job.

        This hook only identifies reviewed problems owned by the plugin. The
        decision to send an undeclared stem to the Chinese graph generator is
        made by ``application.subject_detection`` before this hook is reached.
        """

        del text
        return None

    def build_graph(self, problem: Problem | ProblemDraft) -> SolutionGraph:
        if isinstance(problem, Problem):
            return problem.graph
        if self._generator is None:
            raise GraphBuildFailed(
                "disabled",
                detail="语文插件没有接建图器；生成语文步骤图需要 LLMGraphGenerator",
            )
        return self._generator.generate(problem).graph

    def aligner_for(self, problem: Problem) -> StepAligner:
        """NONE-tier prose: clause-level existence matching (S8)."""

        del problem
        return self._aligner

    def probes_for(self, node: SolutionNode) -> tuple[Probe, ...]:
        """A NONE-tier subject never probes, whatever the graph contains."""

        del node
        return ()

    def evidence_model(self, graph: SolutionGraph) -> EvidenceModel:
        """No evidence model: there is no posterior to update."""

        del graph
        return EvidenceModel(weights={})

    def verify(self, step: StudentStep) -> Verdict:
        """Always ``unknown`` — and it says why, instead of pretending.

        A language answer can be checked for spelling or length, but neither is
        evidence that the *step* was done correctly, so neither is returned.
        """

        del step
        return Verdict(
            status="unknown",
            detail="NONE 档没有可自动验证的真值：本节只给结构提示，不对步骤或答案作判断",
        )
